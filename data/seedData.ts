// Helper to generate ISO date strings relative to today (dayOffset: negative = past, positive = future)
export const getRelativeDate = (dayOffset: number): string => {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  return d.toISOString().split("T")[0];
};

